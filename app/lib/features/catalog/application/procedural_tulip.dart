import 'dart:math' as math;
import 'dart:typed_data';
import 'dart:ui' show Color;

import 'package:flutter_scene/scene.dart';
import 'package:vector_math/vector_math.dart';

import 'render_utils.dart';

/// Builds a flower entirely from code, keyed by the catalog's `procedural` field.
typedef ProceduralFlowerBuilder = Node Function(Color accent);

const Map<String, ProceduralFlowerBuilder> proceduralFlowerBuilders = {
  'tulip': buildTulip,
};

/// Returns the node for [name], or `null` when no builder is registered.
Node? buildProceduralFlower(String name, Color accent) {
  return proceduralFlowerBuilders[name]?.call(accent);
}

/// A faithful Dart port of the viewer's `createProceduralTulip`.
///
/// Three.js builds the petals with `LatheGeometry`; this uses
/// [MeshGeometry.fromArrays] to revolve the same profile, and a sampled
/// triangle strip for the curved leaf.
Node buildTulip(Color accent) {
  final group = Node(name: 'tulip');
  group.add(_stem());
  group.add(
    _leaf(position: Vector3(-0.35, 1.2, 0), rotation: Vector3(0, -0.4, -0.6)),
  );
  group.add(
    _leaf(position: Vector3(0.35, 1.2, 0), rotation: Vector3(0, 0.4, 0.6)),
  );
  group.add(_petals(accent));
  return group;
}

Node _stem() {
  final node = Node(
    name: 'stem',
    mesh: Mesh(
      CylinderGeometry(
        bottomRadius: 0.16,
        topRadius: 0.12,
        height: 3.2,
        radialSegments: 8,
      ),
      flowerMaterial(const Color(0xFF388E3C), roughness: 0.8),
    ),
  );
  node.position = Vector3(0, 1.6, 0);
  return node;
}

Node _leaf({required Vector3 position, required Vector3 rotation}) {
  final group = Node(name: 'leaf');
  group.position = position;
  group.rotation = eulerQuaternion(rotation);

  final blade = Node(
    name: 'leaf-blade',
    mesh: Mesh(
      _leafGeometry(),
      flowerMaterial(
        const Color(0xFF4CAF50),
        roughness: 0.6,
        doubleSided: true,
      ),
    ),
  );
  blade.scale = Vector3(0.8, 0.8, 1);
  blade.rotation = eulerQuaternion(Vector3(0, math.pi / 2, math.pi / 2));
  group.add(blade);
  return group;
}

Node _petals(Color accent) {
  final group = Node(name: 'petals');

  for (var i = 0; i < 6; i++) {
    final angle = (i / 6) * math.pi * 2;
    group.add(
      _petal(
        color: accent,
        geometry: _outerPetalGeometry(),
        position: Vector3(0, 1.2, 0),
        scale: Vector3(1.4, 1, 1.4),
        euler: Vector3(0.25, angle, math.sin(angle) * 0.15),
      ),
    );
  }

  for (var i = 0; i < 6; i++) {
    final angle = (i / 6) * math.pi * 2 + math.pi / 6;
    group.add(
      _petal(
        color: const Color(0xFFFF6F61),
        geometry: _innerPetalGeometry(),
        position: Vector3(0, 1.1, 0),
        scale: Vector3(1, 0.9, 1),
        euler: Vector3(0.15, angle, math.sin(angle) * 0.1),
      ),
    );
  }

  return group;
}

Node _petal({
  required Color color,
  required MeshGeometry geometry,
  required Vector3 position,
  required Vector3 scale,
  required Vector3 euler,
}) {
  final node = Node(
    name: 'petal',
    mesh: Mesh(
      geometry,
      flowerMaterial(color, roughness: 0.3, doubleSided: true),
    ),
  );
  node.position = position;
  node.scale = scale;
  node.rotation = eulerQuaternion(euler);
  return node;
}

// The petal geometry is identical for every petal at a given tessellation, so
// build it once. Nodes can share GPU geometry safely.
MeshGeometry? _outerPetal;
MeshGeometry? _innerPetal;

MeshGeometry _outerPetalGeometry() =>
    _outerPetal ??= _latheGeometry(radialSegments: 12);

MeshGeometry _innerPetalGeometry() =>
    _innerPetal ??= _latheGeometry(radialSegments: 10);

/// Revolves the tulip petal profile (`x = sin(tπ)(0.05 + 0.35t)`, `y = 2.2t`)
/// around the Y axis. Normals are generated by [MeshGeometry.fromArrays].
MeshGeometry _latheGeometry({required int radialSegments}) {
  const profileSegments = 6;
  const height = 2.2;

  final profile = <Vector2>[];
  for (var i = 0; i <= profileSegments; i++) {
    final t = i / profileSegments;
    profile.add(Vector2(math.sin(t * math.pi) * (0.05 + t * 0.35), t * height));
  }

  final positions = <double>[];
  for (final point in profile) {
    for (var j = 0; j <= radialSegments; j++) {
      final phi = (j / radialSegments) * math.pi * 2;
      positions.addAll([
        point.x * math.cos(phi),
        point.y,
        point.x * math.sin(phi),
      ]);
    }
  }

  final stride = radialSegments + 1;
  final indices = <int>[];
  for (var i = 0; i < profile.length - 1; i++) {
    for (var j = 0; j < radialSegments; j++) {
      final a = i * stride + j;
      final b = a + 1;
      final c = a + stride;
      final d = c + 1;
      indices.addAll([a, c, b, b, c, d]);
    }
  }

  return MeshGeometry.fromArrays(
    positions: Float32List.fromList(positions),
    indices: indices,
  );
}

/// The viewer's curved leaf, sampled as a triangle strip between its two
/// quadratic edges.
MeshGeometry _leafGeometry({int segments = 16}) {
  final start = Vector2(0, 0);
  final end = Vector2(1.2, 0.2);
  final topControl = Vector2(0.5, 0.3);
  final bottomControl = Vector2(0.5, -0.05);

  final positions = <double>[];
  for (var i = 0; i <= segments; i++) {
    final t = i / segments;
    final top = _quadratic(start, topControl, end, t);
    final bottom = _quadratic(start, bottomControl, end, t);
    positions.addAll([top.x, top.y, 0, bottom.x, bottom.y, 0]);
  }

  final indices = <int>[];
  for (var i = 0; i < segments; i++) {
    final a = i * 2;
    final b = a + 1;
    final c = a + 2;
    final d = a + 3;
    indices.addAll([a, b, c, c, b, d]);
  }

  return MeshGeometry.fromArrays(
    positions: Float32List.fromList(positions),
    indices: indices,
  );
}

Vector2 _quadratic(Vector2 a, Vector2 b, Vector2 c, double t) {
  final mt = 1 - t;
  return a * (mt * mt) + b * (2 * mt * t) + c * (t * t);
}
